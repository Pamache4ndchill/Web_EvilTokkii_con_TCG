-- 1. Crear la tabla most_streamed
CREATE TABLE IF NOT EXISTS public.most_streamed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL DEFAULT 'Nuevo Juego',
    image_url TEXT DEFAULT '',
    description TEXT DEFAULT '',
    order_index INTEGER DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.most_streamed ENABLE ROW LEVEL SECURITY;

-- 3. Políticas de seguridad (RLS): Lectura pública para la Web y escritura para el Builder
DROP POLICY IF EXISTS "Permitir lectura publica de most_streamed" ON public.most_streamed;
CREATE POLICY "Permitir lectura publica de most_streamed"
ON public.most_streamed FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "Permitir insercion para anon y authenticated en most_streamed" ON public.most_streamed;
CREATE POLICY "Permitir insercion para anon y authenticated en most_streamed"
ON public.most_streamed FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir actualizacion para anon y authenticated en most_streamed" ON public.most_streamed;
CREATE POLICY "Permitir actualizacion para anon y authenticated en most_streamed"
ON public.most_streamed FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir eliminacion para anon y authenticated en most_streamed" ON public.most_streamed;
CREATE POLICY "Permitir eliminacion para anon y authenticated en most_streamed"
ON public.most_streamed FOR DELETE
TO anon, authenticated
USING (true);

-- 4. Habilitar Realtime (opcional para cambios en vivo)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'most_streamed'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.most_streamed;
    END IF;
EXCEPTION
    WHEN OTHERS THEN NULL;
END $$;

